export const CONTACT_FIELDS = [
  "firstName", "lastName", "company", "email", "phone", "message",
] as const;

export type ContactField = (typeof CONTACT_FIELDS)[number];
export type ContactFieldValues = Record<ContactField, string>;
export type ContactFieldErrorCode =
  | "required" | "invalidEmail" | "invalidPhone"
  | "maxLength" | "minLength" | "invalidValue";
export type ContactFieldErrors = Partial<Record<ContactField, ContactFieldErrorCode>>;

export const CONTACT_FIELD_LIMITS: Record<ContactField, { min: number; max: number }> = {
  firstName: { min: 1, max: 80 },
  lastName: { min: 1, max: 80 },
  company: { min: 0, max: 120 },
  email: { min: 3, max: 254 },
  phone: { min: 0, max: 40 },
  message: { min: 10, max: 5000 },
};

const CONTROL_CHARACTERS = /[\u0000-\u001f\u007f]/u;
const MESSAGE_CONTROL_CHARACTERS = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/u;
const EMAIL_PATTERN = /^[A-Z0-9.!#$%&'*+/=?^_{}|~-]+@[A-Z0-9](?:[A-Z0-9-]{0,61}[A-Z0-9])?(?:\.[A-Z0-9](?:[A-Z0-9-]{0,61}[A-Z0-9])?)+$/iu;
const PHONE_PATTERN = /^[+()\d\s./-]+$/u;
const ERROR_CODES = new Set<ContactFieldErrorCode>([
  "required", "invalidEmail", "invalidPhone", "maxLength", "minLength", "invalidValue",
]);

export function isContactField(value: unknown): value is ContactField {
  return typeof value === "string" && CONTACT_FIELDS.some((field) => field === value);
}

/** Keeps the browser and API on the same normalization and field limits. */
export function validateContactFields(input: Record<string, unknown>):
  | { ok: true; values: ContactFieldValues }
  | { ok: false; fieldErrors: ContactFieldErrors } {
  const values = {} as ContactFieldValues;
  const fieldErrors: ContactFieldErrors = {};

  for (const field of CONTACT_FIELDS) {
    const raw = input[field];
    if (typeof raw !== "string") {
      fieldErrors[field] = "invalidValue";
      continue;
    }

    const normalized = (field === "message" ? raw.replace(/\r\n?/gu, "\n") : raw)
      .trim().normalize("NFC");
    const { min, max } = CONTACT_FIELD_LIMITS[field];
    const controls = field === "message" ? MESSAGE_CONTROL_CHARACTERS : CONTROL_CHARACTERS;
    if (normalized.length === 0 && min > 0) {
      fieldErrors[field] = "required";
    } else if (normalized.length > max) {
      fieldErrors[field] = "maxLength";
    } else if (controls.test(normalized)) {
      fieldErrors[field] = "invalidValue";
    } else if (field === "email" && !EMAIL_PATTERN.test(normalized)) {
      fieldErrors[field] = "invalidEmail";
    } else if (field === "phone" && normalized && !PHONE_PATTERN.test(normalized)) {
      fieldErrors[field] = "invalidPhone";
    } else if (normalized.length < min) {
      fieldErrors[field] = "minLength";
    } else {
      values[field] = field === "email" ? normalized.toLowerCase() : normalized;
    }
  }

  return Object.keys(fieldErrors).length
    ? { ok: false, fieldErrors }
    : { ok: true, values };
}

/** Accept only field names and codes generated by this validator. */
export function readContactFieldErrors(value: unknown): ContactFieldErrors {
  if (typeof value !== "object" || value === null || Array.isArray(value)) return {};
  const input = value as Record<string, unknown>;
  const fieldErrors: ContactFieldErrors = {};
  for (const field of CONTACT_FIELDS) {
    const code = input[field];
    if (typeof code === "string" && ERROR_CODES.has(code as ContactFieldErrorCode)) {
      fieldErrors[field] = code as ContactFieldErrorCode;
    }
  }
  return fieldErrors;
}
